using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Infrastructure;
using Microsoft.EntityFrameworkCore.Migrations;
using Microsoft.Extensions.Configuration;
using ProCoderJi.Api.Configuration;
using ProCoderJi.Api.Data;

namespace ProCoderJi.Api.Tests;

public sealed class RelationalDatabaseConfigurationTests
{
    [Theory]
    [InlineData("Postgres")]
    [InlineData("SqlServer")]
    [InlineData("unsupported")]
    public void HostedProvidersRequireAnExplicitConnection(string provider)
    {
        var settings = Configuration(provider, null);
        Assert.Throws<InvalidOperationException>(() => RelationalDatabaseConfiguration.Configure(new DbContextOptionsBuilder(), settings, Path.GetTempPath()));
    }

    [Fact]
    public void SqlServerMigrationUsesIdentityAndSqlServerLengthConstraints()
    {
        using var db = Context("SqlServer", "Server=localhost;Database=script_only;User Id=sa;Password=unused");
        var sql = db.GetService<IMigrator>().GenerateScript();
        Assert.Contains("CREATE TABLE [Users]", sql);
        Assert.Contains("CREATE TABLE [ContactMessages]", sql);
        Assert.Contains("CREATE UNIQUE INDEX [IX_ContactMessages_CaptchaTokenHash]", sql);
        Assert.Contains("IDENTITY", sql);
        Assert.Contains("DATALENGTH([QuestionIdsJson]) <= 8192", sql);
        Assert.Contains("DATALENGTH([ResponsesJson]) <= 16384", sql);
        Assert.DoesNotContain("length(\"QuestionIdsJson\")", sql);
        Assert.False(db.Database.CreateExecutionStrategy().RetriesOnFailure);
        Assert.False(db.Database.HasPendingModelChanges());
    }

    [Fact]
    public void PostgresMigrationKeepsItsIdentityAndLengthConstraints()
    {
        using var db = Context("Postgres", "Host=localhost;Database=script_only;Username=unused;Password=unused");
        var sql = db.GetService<IMigrator>().GenerateScript();
        Assert.Contains("GENERATED BY DEFAULT AS IDENTITY", sql);
        Assert.Contains("length(\"QuestionIdsJson\") <= 4096", sql);
        Assert.DoesNotContain("DATALENGTH", sql);
        Assert.False(db.Database.HasPendingModelChanges());
    }

    [Fact]
    public void SqliteMigrationKeepsAutoincrementAndLengthConstraints()
    {
        using var db = Context("Sqlite", "Data Source=:memory:");
        var sql = db.GetService<IMigrator>().GenerateScript();
        Assert.Contains("AUTOINCREMENT", sql);
        Assert.Contains("length(\"QuestionIdsJson\") <= 4096", sql);
        Assert.DoesNotContain("DATALENGTH", sql);
        Assert.False(db.Database.HasPendingModelChanges());
    }

    private static IConfiguration Configuration(string provider, string? connection) => new ConfigurationBuilder()
        .AddInMemoryCollection(new Dictionary<string, string?>
        {
            ["Database:Provider"] = provider,
            ["ConnectionStrings:Platform"] = connection
        }).Build();

    private static PlatformDbContext Context(string provider, string connection)
    {
        var options = new DbContextOptionsBuilder<PlatformDbContext>();
        RelationalDatabaseConfiguration.Configure(options, Configuration(provider, connection), Path.GetTempPath());
        return new PlatformDbContext(options.Options);
    }
}
